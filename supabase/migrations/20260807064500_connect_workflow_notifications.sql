create or replace function app_private.get_header_notification_center(
  p_limit integer default 20
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select app_private.current_app_user_id());
  v_tenant_id uuid := (select app_private.current_user_tenant_id());
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 50);
  v_result jsonb;
begin
  if (select auth.uid()) is null or v_user_id is null or v_tenant_id is null then
    raise exception '当前登录用户未绑定业务账号' using errcode = '42501';
  end if;

  select jsonb_build_object(
    'notices', coalesce((
      select jsonb_agg(row_data order by create_time desc)
      from (
        select jsonb_build_object(
          'id', n.id,
          'category', n.category,
          'title', n.title,
          'content', n.content,
          'severity', n.severity,
          'isRead', n.is_read,
          'createdAt', n.create_time,
          'routePath', n.route_path,
          'routeQuery', n.route_query,
          'instanceId', n.instance_id
        ) row_data, n.create_time
        from public.sys_notification n
        where n.tenant_id = v_tenant_id
          and n.recipient_user_id = v_user_id
          and n.category = 'notice'
        order by n.create_time desc
        limit v_limit
      ) rows
    ), '[]'::jsonb),
    'messages', coalesce((
      select jsonb_agg(row_data order by create_time desc)
      from (
        select jsonb_build_object(
          'id', n.id,
          'category', n.category,
          'title', n.title,
          'content', n.content,
          'severity', n.severity,
          'isRead', n.is_read,
          'createdAt', n.create_time,
          'routePath', n.route_path,
          'routeQuery', n.route_query,
          'instanceId', n.instance_id
        ) row_data, n.create_time
        from public.sys_notification n
        where n.tenant_id = v_tenant_id
          and n.recipient_user_id = v_user_id
          and n.category = 'message'
        order by n.create_time desc
        limit v_limit
      ) rows
    ), '[]'::jsonb),
    'todos', coalesce((
      select jsonb_agg(row_data order by create_time desc)
      from (
        select jsonb_build_object(
          'id', n.id,
          'category', n.category,
          'title', n.title,
          'content', n.content,
          'severity', n.severity,
          'isRead', n.is_read,
          'createdAt', n.create_time,
          'routePath', n.route_path,
          'routeQuery', n.route_query,
          'instanceId', n.instance_id
        ) row_data, n.create_time
        from public.sys_notification n
        where n.tenant_id = v_tenant_id
          and n.recipient_user_id = v_user_id
          and n.category = 'todo'
          and n.is_read = false
        order by n.create_time desc
        limit v_limit
      ) rows
    ), '[]'::jsonb),
    'unreadNoticeCount', (
      select count(*) from public.sys_notification n
      where n.tenant_id = v_tenant_id and n.recipient_user_id = v_user_id
        and n.category = 'notice' and n.is_read = false
    ),
    'unreadMessageCount', (
      select count(*) from public.sys_notification n
      where n.tenant_id = v_tenant_id and n.recipient_user_id = v_user_id
        and n.category = 'message' and n.is_read = false
    ),
    'pendingTodoCount', (
      select count(*) from public.sys_notification n
      where n.tenant_id = v_tenant_id and n.recipient_user_id = v_user_id
        and n.category = 'todo' and n.is_read = false
    )
  ) into v_result;

  return v_result || jsonb_build_object(
    'totalUnreadCount',
    coalesce((v_result ->> 'unreadNoticeCount')::integer, 0)
      + coalesce((v_result ->> 'unreadMessageCount')::integer, 0)
      + coalesce((v_result ->> 'pendingTodoCount')::integer, 0)
  );
end;
$$;
create or replace function app_private.mark_header_notifications_read(
  p_category text default null,
  p_notification_ids uuid[] default null
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select app_private.current_app_user_id());
  v_tenant_id uuid := (select app_private.current_user_tenant_id());
  v_count integer;
begin
  if (select auth.uid()) is null or v_user_id is null or v_tenant_id is null then
    raise exception '当前登录用户未绑定业务账号' using errcode = '42501';
  end if;
  if p_category is not null and p_category not in ('notice', 'message') then
    raise exception '待办事项需完成审批后自动归档';
  end if;

  update public.sys_notification n
  set is_read = true,
      read_at = coalesce(n.read_at, now())
  where n.tenant_id = v_tenant_id
    and n.recipient_user_id = v_user_id
    and n.category in ('notice', 'message')
    and n.is_read = false
    and (p_category is null or n.category = p_category)
    and (p_notification_ids is null or n.id = any(p_notification_ids));

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;
