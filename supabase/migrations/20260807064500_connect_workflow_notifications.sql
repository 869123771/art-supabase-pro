insert into public.sys_notification(
  recipient_user_id,
  category,
  title,
  content,
  severity,
  source_type,
  source_id,
  business_type,
  business_id,
  instance_id,
  route_path,
  route_query,
  tenant_id
)
select
  t.assignee_user_id,
  'todo',
  '待审批：' || i.business_title,
  i.initiator_name_snapshot || ' 提交至“' || t.node_name || '”节点',
  case when t.due_at is not null and t.due_at <= now() + interval '4 hours'
    then 'danger' else 'warning' end,
  'workflow_task',
  t.id,
  i.business_type,
  i.business_id,
  i.id,
  '/workflow/workbench',
  jsonb_build_object('tab', 'pending', 'instanceId', i.id),
  t.tenant_id
from public.wf_task t
join public.wf_instance i on i.id = t.instance_id
where t.status = 'pending'
on conflict (recipient_user_id, category, source_type, source_id) do nothing;
